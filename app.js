function getCalculatedValues() {
  const selectCustomer = document.getElementById('calc-customer-select');
  const selectService = document.getElementById('calc-service-select');
  const inputUnits = document.getElementById('calc-units-input');
  const manualPriceInput = document.getElementById('calc-manual-price-input');
  const inputTrip = document.getElementById('calc-trip-input');
  const inputDiscount = document.getElementById('calc-discount-input');
  const inputReceived = document.getElementById('calc-received-input');

  const cust = getSelectedCustomer();
  const item = implementsData.find(i => i.id === (selectService ? selectService.value : '9-kalapai')) || implementsData[0];
  const isTankerOrCarrier = (item.id === 'water-tanker' || item.id === 'goods-carrier');

  let grossTotal = 0;
  let rateDisplay = "";
  let toolUnits = "";

  if (isTankerOrCarrier) {
    grossTotal = parseFloat(manualPriceInput?.value) || 0;
    const trips = inputTrip ? inputTrip.value : '2';
    if (item.id === 'water-tanker') {
      rateDisplay = `${trips} Trips (@ ₹${item.rate})`;
      toolUnits = `${trips} Trips`;
    } else {
      rateDisplay = `${trips} KM (@ ₹${item.rate})`;
      toolUnits = `${trips} KM`;
    }
  } else {
    const rate = item.rate;
    const units = parseFloat(inputUnits?.value) || 1;
    grossTotal = rate * units;
    rateDisplay = `₹${rate} / ${item.pricingType}`;
    toolUnits = `${units} hrs`;
  }

  const discount = Math.max(0, parseFloat(inputDiscount?.value) || 0);
  const todayNet = Math.max(0, grossTotal - discount);
  const pastBalance = cust ? (cust.pastBalance || 0) : 0;
  const totalPayable = pastBalance + todayNet;
  const receivedNow = Math.max(0, parseFloat(inputReceived?.value) || 0);
  const finalBalance = Math.max(0, totalPayable - receivedNow);

  return {
    cust,
    toolName: currentLang === 'ta' ? item.nameTa : item.nameEn,
    toolUnits,
    rateDisplay,
    grossTotal,
    discount,
    todayNet,
    pastBalance,
    totalPayable,
    receivedNow,
    finalBalance
  };
}

function updateCalculator() {
  const calc = getCalculatedValues();
  if (!calc) return;

  const receiptCustName = document.getElementById('receipt-customer-name');
  const receiptService = document.getElementById('receipt-selected-service');
  const receiptRate = document.getElementById('receipt-default-rate');
  const receiptGross = document.getElementById('receipt-gross-total');
  const receiptDiscount = document.getElementById('receipt-discount');
  const receiptNet = document.getElementById('receipt-net-total');
  const receiptPastBal = document.getElementById('receipt-past-balance');
  const receiptTotalPayable = document.getElementById('receipt-total-payable');
  const receiptReceived = document.getElementById('receipt-amount-received');
  const receiptBalanceDue = document.getElementById('receipt-balance-due');

  if (receiptCustName && calc.cust) receiptCustName.textContent = calc.cust.name;
  if (receiptService) receiptService.textContent = calc.toolName;
  if (receiptRate) receiptRate.textContent = calc.rateDisplay;
  if (receiptGross) receiptGross.textContent = `₹${calc.grossTotal.toLocaleString('en-IN')}`;
  if (receiptDiscount) receiptDiscount.textContent = `- ₹${calc.discount.toLocaleString('en-IN')}`;
  if (receiptNet) receiptNet.textContent = `₹${calc.todayNet.toLocaleString('en-IN')}`;
  if (receiptPastBal) receiptPastBal.textContent = `+ ₹${calc.pastBalance.toLocaleString('en-IN')}`;
  if (receiptTotalPayable) receiptTotalPayable.textContent = `₹${calc.totalPayable.toLocaleString('en-IN')}`;
  if (receiptReceived) receiptReceived.textContent = `− ₹${calc.receivedNow.toLocaleString('en-IN')}`;
  if (receiptBalanceDue) receiptBalanceDue.textContent = `₹${calc.finalBalance.toLocaleString('en-IN')}`;
}

