function handleToolChange() {
  const selectService = document.getElementById('calc-service-select');
  const hourlyGroup = document.getElementById('calc-hourly-group');
  const manualAmountGroup = document.getElementById('calc-manual-amount-group');
  const manualPriceInput = document.getElementById('calc-manual-price-input');
  const tripLabel = document.getElementById('calc-trip-label');
  const rateHelper = document.getElementById('calc-rate-helper');
  const inputTrip = document.getElementById('calc-trip-input');

  const selectedToolId = selectService.value;
  const isTankerOrCarrier = (selectedToolId === 'water-tanker' || selectedToolId === 'goods-carrier');

  if (isTankerOrCarrier) {
    hourlyGroup.style.display = 'none';
    manualAmountGroup.style.display = 'block';

    const item = implementsData.find(i => i.id === selectedToolId);
    if (selectedToolId === 'water-tanker') {
      tripLabel.textContent = currentLang === 'ta' ? "டிரிப் / லோடு எண்ணிக்கை:" : "Number of Trips / Loads:";
      rateHelper.textContent = `(@ ₹${item.rate} / trip)`;
      if (!inputTrip.value || parseInt(inputTrip.value) > 10) inputTrip.value = 2;
      manualPriceInput.value = (parseInt(inputTrip.value) || 2) * item.rate;
    } else {
      tripLabel.textContent = currentLang === 'ta' ? "கிலோமீட்டர் (KM):" : "Approx Kilometres (KM):";
      rateHelper.textContent = `(@ ₹${item.rate} / km)`;
      if (!inputTrip.value || parseInt(inputTrip.value) < 10) inputTrip.value = 30;
      manualPriceInput.value = (parseInt(inputTrip.value) || 30) * item.rate;
    }
  } else {
    hourlyGroup.style.display = 'block';
    manualAmountGroup.style.display = 'none';
  }
}

